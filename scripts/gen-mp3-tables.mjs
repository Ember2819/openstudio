#!/usr/bin/env node
// Regenerates src/audio/mp3tables.js — the ISO 11172-3 Layer III Huffman codes and synthesis window — from PDMP3
// (public domain, https://github.com/technosaurus/PDMP3), whose decoder keeps them as trees.
//   node scripts/gen-mp3-tables.mjs path/to/pdmp3.c
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = readFileSync(process.argv[2], 'utf8');
const block = (start) => { const a = src.indexOf(start); return src.slice(a, src.indexOf('};', a)).replace(/\/\/[^\n]*/g, ''); };
const nums = [...block('static const unsigned short g_huffman_table[] = {').matchAll(/0x[0-9a-fA-F]+/g)].map((m) => parseInt(m[0], 16));
const entries = [...block('hufftables g_huffman_main').matchAll(/\{\s*(NULL|g_huffman_table\s*(?:\+\s*(\d+))?)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}\s*,?\s*\/\*\s*Table\s+(\d+)/g)]
  .map((m) => ({ off: m[1] === 'NULL' ? -1 : Number(m[2] || 0), len: Number(m[3]), table: Number(m[5]) }));

/** Every leaf of a tree: value -> [bits, code]. */
function walk(off, len) {
  const out = new Map();
  const rec = (point, code, bits) => {
    const v = nums[off + point];
    if ((v & 0xff00) === 0) { out.set(v & 0xff, [bits, code]); return; }
    for (const bit of [0, 1]) {
      let p = point;
      const step = (x) => (bit ? x & 0xff : x >> 8);
      while (step(nums[off + p]) >= 250) p += step(nums[off + p]);
      p += step(nums[off + p]);
      if (p >= len || bits > 20) throw new Error('bad tree');
      rec(p, (code << 1) | bit, bits + 1);
    }
  };
  rec(0, 0, 0);
  return out;
}

const tables = {};
for (const e of entries) {
  // 17-23 share 16's codes and 25-31 share 24's (they differ only in linbits); 32 / 33 are the count1 tables
  if (e.off < 0 || !e.len || e.table > 31 || (e.table > 16 && e.table < 24) || e.table > 24) continue;
  const map = walk(e.off, e.len);
  const dim = Math.max(...[...map.keys()].map((k) => Math.max(k >> 4, k & 15))) + 1;
  const codes = [];
  for (let x = 0; x < dim; x++) for (let y = 0; y < dim; y++) { const [b, c] = map.get((x << 4) | y); codes.push(b * 2 ** 20 + c); }
  tables[e.table] = codes;
}
const a = walk(2742, 31); // count1 table A
tables[32] = Array.from({ length: 16 }, (_, v) => a.get(v)[0] * 2 ** 20 + a.get(v)[1]);
const window = [...block('g_synth_dtbl[512] = {').matchAll(/-?\d+\.\d+/g)].map((m) => Number(m[0]));
if (window.length !== 512) throw new Error(`synthesis window has ${window.length} values`);

const out = `// Generated by scripts/gen-mp3-tables.mjs from PDMP3 (public domain) — do not edit.
// ISO 11172-3 Layer III Huffman codes: HUFFMAN[table][x * dim + y] = bits * 2^20 + code (tables 17-23 use 16's codes,
// 25-31 use 24's; 32 is count1 table A), and the synthesis window D (the analysis window is D / 32).
export const HUFFMAN = {
${Object.entries(tables).map(([t, c]) => `  ${t}: [${c.join(',')}],`).join('\n')}
};
export const SYNTH_WINDOW = [${window.join(',')}];
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '../src/audio/mp3tables.js'), out);
console.log('wrote src/audio/mp3tables.js');
